function r2(n) {
  return Math.round(n * 100) / 100;
}

// Helper to verify wall lines & compute exact centerline
function buildSegment(cfg) {
  const {
    id,
    branch,
    order_in_branch,
    wall_handles,
    seam_or_end_handles = [],
    x1,
    y1,
    x2,
    y2,
    W,
    H,
    bod_ffl,
    size_source,
    bod_source,
    size_mtext_handle = null,
    bod_mtext_handle = null,
    upstream_conn,
    downstream_conn,
    notes = "",
  } = cfg;

  const length_mm = r2(Math.hypot(x2 - x1, y2 - y1));
  const angle_deg = r2((Math.atan2(y2 - y1, x2 - x1) * 180) / Math.PI);
  const size_mtext = size_mtext_handle ? byHandle.get(size_mtext_handle) : null;
  const bod_mtext = bod_mtext_handle ? byHandle.get(bod_mtext_handle) : null;

  return {
    id,
    system: "SEAD",
    system_full_name: "Smoke Exhaust Air Duct (Ống gió hút khói tầng hầm B1)",
    design_layer: "MEPG-AC-M-Hút khói-Smoke Exhaust Air-SED",
    spec_target_layer: "M-MVAC-SEAD",
    spec_target_color_aci: 190,
    branch,
    order_in_branch,
    centerline: {
      x1: r2(x1),
      y1: r2(y1),
      x2: r2(x2),
      y2: r2(y2),
    },
    length_mm,
    angle_deg,
    width_W: W,
    height_H: H,
    bod_ffl,
    center_z_ffl: bod_ffl !== null && H !== null ? r2(bod_ffl + H / 2) : null,
    tod_ffl: bod_ffl !== null && H !== null ? r2(bod_ffl + H) : null,
    size_source,
    bod_source,
    labels: {
      size_mtext_handle,
      size_text_live: size_mtext ? size_mtext.text : null,
      size_text_disk: size_mtext ? size_mtext.diskText || size_mtext.text : null,
      size_pos: size_mtext ? [r2(size_mtext.pos[0]), r2(size_mtext.pos[1])] : null,
      bod_mtext_handle,
      bod_text: bod_mtext ? bod_mtext.text : null,
      bod_pos: bod_mtext ? [r2(bod_mtext.pos[0]), r2(bod_mtext.pos[1])] : null,
    },
    wall_handles,
    seam_or_end_handles,
    upstream_conn,
    downstream_conn,
    notes,
  };
}

